List<FoodSearchResult> searchFilipino(String query) {
  final q = query.toLowerCase().trim();
  if (q.isEmpty) return filipinoFoods;
  return filipinoFoods
      .where((f) =>
          f.name.toLowerCase().contains(q) ||
          (f.description?.toLowerCase().contains(q) ?? false))
      .toList();
}
